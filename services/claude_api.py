async def generate_mnemonic(term: str, definition: str) -> str:
    """Генерирует мнемонику для термина через Claude API"""
    client = anthropic.Anthropic(api_key=os.getenv("ANTHROPIC_API_KEY"))
    
    message = await asyncio.to_thread(
        client.messages.create,
        model="claude-haiku-4-5-20251001",
        max_tokens=1000,
        system=SYSTEM_PROMPT,
        messages=[
            {
                "role": "user",
                "content": f"Термин: {term}\nОпределение: {definition}\nПридумай НОВЫЙ оригинальный образ, непохожий на предыдущие!"
            }
        ]
    )
    return message.content[0].text


async def find_term_by_meaning(user_input: str, terms_list: list) -> str:
    """Находит термин по смыслу, опечаткам или описанию"""
    client = anthropic.Anthropic(api_key=os.getenv("ANTHROPIC_API_KEY"))
    terms_str = "\n".join(terms_list)

    message = await asyncio.to_thread(
        client.messages.create,
        model="claude-haiku-4-5-20251001",
        max_tokens=100,
        messages=[
            {
                "role": "user",
                "content": f"""У тебя есть список терминов по генетике:
{terms_str}

Пользователь написал: "{user_input}"

Найди наиболее подходящий термин из списка.
Учитывай опечатки, синонимы и описания смысла.
Если ничего не подходит — ответь словом: НЕТ

Ответь ТОЛЬКО одним словом — термином из списка или НЕТ."""
            }
        ]
    )

    result = message.content[0].text.strip().lower()
    if result == "нет":
        return None
    return result